"""Generate chassis_offline.generated.lua: the offline chassis graphic of every
model (chassisOfflineSvg from port_card.lua, drawn by the plugin's own Lua),
base64-encoded so GetControlLayout can place it as a static Svg graphic
without encoding anything in Designer.

Usage (from the repo root, plain python: lupa lives in the user site):
    python tools/gen_offline_chassis.py
Run it again after any change to chassis_layout.lua or port_card.lua."""
import base64, io, os, lupa

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUTPUT = "chassis_offline.generated.lua"


def generate(root):
    lua = lupa.LuaRuntime(unpack_returned_tuples=True)
    for name in ("chassis_layout.lua", "port_card.lua"):
        lua.execute(io.open(os.path.join(root, name), encoding="utf-8-sig").read())
    g = lua.globals()
    lines = [
        "-- Auto-generated by tools/gen_offline_chassis.py, do not edit.",
        "-- Offline chassis graphic per model: base64 of chassisOfflineSvg(model).",
        "CHASSIS_OFFLINE_SVG = {",
    ]
    for model in sorted(g.CHASSIS_LAYOUT.keys()):
        svg = g.chassisOfflineSvg(model)
        lines.append('  ["%s"] = "%s",' % (model, base64.b64encode(svg.encode("utf-8")).decode("ascii")))
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    content = generate(ROOT)
    path = os.path.join(ROOT, OUTPUT)
    # Rewrite only on a real change: the checkout may hold CRLF (autocrlf),
    # and an LF rewrite of identical content shows as modified in git status.
    current = io.open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if current == content:
        print(f"{OUTPUT} is up to date")
    else:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"wrote {OUTPUT} ({len(content)} bytes)")
